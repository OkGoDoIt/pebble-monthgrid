#!/usr/bin/env node
'use strict';
// Packs the settings page (src/settings + src/pkjs/model.js) into one HTML
// document and writes it to src/pkjs/settings_page.js, which the phone opens
// as a data: URI. The build runs this first (wscript); run it by hand to see
// the page's size.
//
//   node tools/build_settings_page.js

const fs = require('fs');
const path = require('path');

const APP = path.resolve(__dirname, '..');
const SRC = path.join(APP, 'src/settings');
const OUT = path.join(APP, 'src/pkjs/settings_page.js');
// Load order matters: each file uses the ones before it.
const SCRIPTS = ['monthgrid-fonts.js', 'monthgrid-face.js', '../pkjs/model.js', 'bar.js', 'core.js', 'event.js', 'page.js'];
// Where the phone puts the page's state and what the watch can do.
const BOOT = '/*MG_BOOT*/';

function read(name) {
  const text = fs.readFileSync(path.join(SRC, name), 'utf8');
  if (/<\/script/i.test(text)) { throw new Error(name + ' contains </script>, which would end the page early'); }
  return text;
}

const html = [
  '<!doctype html><html lang="en"><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
  '<title>MonthGrid</title><style>',
  read('core.css'),
  'html,body{margin:0;height:100%}body{background:#fff}',
  '@media (prefers-color-scheme:dark){body{background:#000}}',
  '#frame{position:relative;height:100%;overflow-y:auto}',
  '</style></head><body><div id="frame"></div>',
  ...SCRIPTS.map((s) => '<script>' + read(s) + '</script>'),
  '<script>var MG_BOOT=' + BOOT + ';MGPage.mount(document.getElementById("frame"),MG_BOOT||{});</script>',
  '</body></html>',
].join('\n');

const out = '// Generated by tools/build_settings_page.js from src/settings; do not edit.\n' +
  '// The settings page as one HTML document; ' + JSON.stringify(BOOT) + ' marks where the phone\n' +
  '// puts {state, ctx, tab}.\n' +
  'module.exports = { html: ' + JSON.stringify(html) + ', boot: ' + JSON.stringify(BOOT) + ' };\n';
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== out) { fs.writeFileSync(OUT, out); }
const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log('settings page: ' + kb(Buffer.byteLength(html)) + ', as a data URI ' +
  kb(Buffer.byteLength(encodeURIComponent(html))));
